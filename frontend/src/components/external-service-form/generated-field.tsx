import { Show, createSignal } from 'solid-js';
import type { Field } from '@opsiforce/external-service-sdk/forms';
import { Button } from '~/components/ui/button';
import { ConfirmDialog } from '~/components/ui/confirm-dialog';
import { KeyRound, RefreshCw } from '~/components/icons';
import { CopyButton } from './copy-button';
import type { FormContext } from './form-context';
import { isKeptSecret } from './form-values';

type GeneratedFieldDefinition = Extract<Field, { type: 'text' | 'secret' }>;

const GENERATED_BOX_CLASS =
  'inline-flex h-8 min-w-0 flex-1 items-center gap-1.5 rounded-md border border-dashed border-border px-2.5 font-mono text-[11px] text-muted-foreground';

function RotateButton(props: { field: GeneratedFieldDefinition; itemId?: string; ctx: FormContext }) {
  const [confirming, setConfirming] = createSignal(false);
  const [rotating, setRotating] = createSignal(false);
  const [failure, setFailure] = createSignal<string | null>(null);
  const label = () => (props.field.label ?? props.field.key).toLowerCase();
  const blocked = () => (props.ctx.draft.isDirty() ? 'Save or discard your changes before rotating.' : undefined);

  const rotate = async () => {
    const run = props.ctx.rotate;
    if (!run) return;
    setRotating(true);
    setFailure(null);
    try {
      await run({ field: props.field.key, ...(props.itemId ? { item: props.itemId } : {}) });
    } catch (error) {
      setFailure(error instanceof Error && error.message ? error.message : `The ${label()} could not be rotated.`);
    } finally {
      setRotating(false);
    }
  };

  return (
    <Show when={props.ctx.rotate && !props.ctx.readOnly()}>
      <Button
        type="button"
        variant="outline"
        size="sm"
        class="h-7 shrink-0 text-xs"
        loading={rotating()}
        disabled={blocked() !== undefined}
        title={blocked()}
        onClick={() => setConfirming(true)}
      >
        <RefreshCw class="h-3 w-3" aria-hidden="true" />
        Rotate
      </Button>
      <Show when={failure()}>
        {(message) => (
          <span class="text-[11px] text-destructive" role="alert">
            {message()}
          </span>
        )}
      </Show>
      <ConfirmDialog
        open={confirming()}
        onOpenChange={setConfirming}
        title={`Rotate the ${label()}?`}
        description={
          props.field.type === 'secret'
            ? 'The old value stops working at once. The new one is shown once, and the service is told about it.'
            : 'The old value stops working at once. Anyone who has it needs the new one.'
        }
        confirmLabel="Rotate"
        variant="destructive"
        onConfirm={() => void rotate()}
      />
    </Show>
  );
}

function RevealedSecret(props: { value: string; label: string }) {
  return (
    <div class="flex flex-col gap-1">
      <div class="flex items-center gap-1.5 rounded-md border border-amber-500/40 bg-amber-500/10 px-2.5 py-1.5">
        <span class="min-w-0 flex-1 break-all font-mono text-[11px]">{props.value}</span>
        <CopyButton text={props.value} label={`Copy ${props.label}`} />
      </div>
      <span class="text-[11px] text-amber-700" role="status">
        Shown once. Copy it now: afterwards it stays encrypted, and a lost value means Rotate.
      </span>
    </div>
  );
}

export function GeneratedField(props: {
  field: GeneratedFieldDefinition;
  value: unknown;
  path: string;
  itemId?: string;
  ctx: FormContext;
}) {
  const pending = () => props.ctx.pendingGeneratedText?.() ?? 'Generated by the platform when you save.';
  const revealed = () => props.ctx.revealed?.().get(props.path);
  const label = () => (props.field.label ?? props.field.key).toLowerCase();
  const text = () => (typeof props.value === 'string' && props.value !== '' ? props.value : undefined);

  return (
    <Show
      when={props.field.type === 'secret'}
      fallback={
        <Show when={text()} fallback={<span class="text-[11px] italic text-muted-foreground">{pending()}</span>}>
          {(generated) => (
            <div class="flex flex-wrap items-center gap-2">
              <div class="flex min-w-0 flex-1 items-center gap-1.5 rounded-md bg-muted/60 px-2.5 py-1.5">
                <span class="min-w-0 flex-1 truncate font-mono text-[11px]">{generated()}</span>
                <CopyButton text={generated()} label={`Copy ${label()}`} />
              </div>
              <RotateButton field={props.field} itemId={props.itemId} ctx={props.ctx} />
            </div>
          )}
        </Show>
      }
    >
      <Show
        when={revealed()}
        fallback={
          <Show
            when={isKeptSecret(props.value)}
            fallback={<span class="text-[11px] italic text-muted-foreground">{pending()}</span>}
          >
            <div class="flex flex-wrap items-center gap-2">
              <span class={GENERATED_BOX_CLASS}>
                <KeyRound class="h-3 w-3 shrink-0" aria-hidden="true" />
                generated by the platform · stored · encrypted
              </span>
              <RotateButton field={props.field} itemId={props.itemId} ctx={props.ctx} />
            </div>
          </Show>
        }
      >
        {(value) => <RevealedSecret value={value()} label={label()} />}
      </Show>
    </Show>
  );
}
